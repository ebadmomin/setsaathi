"""Generate D1 seed migrations from the reference backend's catalogue.

Usage (repo root):  python worker/scripts/generate_seed.py [path/to/setsaathi.db]
Reads exercises (Free Exercise DB, public domain, source/licence metadata kept),
plan_templates and plan_variants from a populated FastAPI SQLite DB and writes
migrations/0002_seed_exercises.sql and migrations/0003_seed_plan_templates.sql.
No user data is read.
"""
import sqlite3
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
db = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "backend" / "setsaathi.db"


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def dump(table, cols, header):
    con = sqlite3.connect(db)
    rows = con.execute(f"SELECT {','.join(cols)} FROM {table} ORDER BY id").fetchall()
    lines = [header] if header else []
    for r in rows:
        lines.append(f"INSERT INTO {table} ({','.join(cols)}) VALUES ({','.join(lit(v) for v in r)});")
    return lines, len(rows)


ex_cols = ["id", "name", "primary_muscle", "secondary_muscles", "category", "equipment", "difficulty", "instructions", "posture", "breathing", "common_mistake", "safety_tips", "substitute", "media_status", "media_url", "source_name", "source_id", "source_url", "license_name", "license_url", "movement_force", "movement_mechanic"]
lines, n = dump("exercises", ex_cols, "-- Generated by worker/scripts/generate_seed.py. Exercise metadata: Free Exercise DB (public domain) plus SetSaathi originals; source/licence columns preserved.")
(root / "migrations" / "0002_seed_exercises.sql").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("exercises", n)
l1, n1 = dump("plan_templates", ["id", "experience", "split", "version", "structure_json", "pools_json", "published"], "-- Generated by worker/scripts/generate_seed.py.")
l2, n2 = dump("plan_variants", ["id", "template_id", "number", "pools_json", "published"], "")
(root / "migrations" / "0003_seed_plan_templates.sql").write_text("\n".join(l1 + l2) + "\n", encoding="utf-8")
print("templates", n1, "variants", n2)
